"""Minimal HTTP service for a private GitHub Codespace."""
from __future__ import annotations

import json
import os
import shutil
from email import policy
from email.parser import BytesParser
from http.server import BaseHTTPRequestHandler, ThreadingHTTPServer
from pathlib import Path
from urllib.parse import urlsplit

from backend import MAX_BYTES, OptimizationError, optimize_pdf

PORT = int(os.getenv("PORT", "8765"))
INDEX = (Path(__file__).parent / "index.html").read_bytes()


class Handler(BaseHTTPRequestHandler):
    def log_message(self, fmt: str, *args: object) -> None:
        # Avoid leaking URLs or document names into access logs.
        print(f"{self.command}: richiesta completata", flush=True)

    def _send(self, code: int, data: bytes, content_type: str,
              extra: dict[str, str] | None = None) -> None:
        self.send_response(code)
        self.send_header("Content-Type", content_type)
        self.send_header("Content-Length", str(len(data)))
        self.send_header("Cache-Control", "no-store, max-age=0")
        self.send_header("X-Content-Type-Options", "nosniff")
        self.send_header("Referrer-Policy", "no-referrer")
        self.send_header("Content-Security-Policy",
                         "default-src 'self'; script-src 'self' 'unsafe-inline'; "
                         "style-src 'self' 'unsafe-inline'; object-src 'none'; frame-ancestors 'none'")
        for key, value in (extra or {}).items():
            self.send_header(key, value)
        self.end_headers()
        self.wfile.write(data)

    def _json(self, code: int, obj: dict) -> None:
        self._send(code, json.dumps(obj, ensure_ascii=False).encode(),
                   "application/json; charset=utf-8")

    def do_GET(self) -> None:
        path = urlsplit(self.path).path
        if path == "/":
            self._send(200, INDEX, "text/html; charset=utf-8")
        elif path == "/health":
            self._json(200, {
                "ready": all(shutil.which(cmd) for cmd in
                             ("recode_pdf", "jbig2", "opj_compress",
                              "opj_decompress", "tesseract", "pdftoppm")),
                "engine": "Internet Archive archive-pdf-tools"
            })
        else:
            self._json(404, {"error": "Pagina non trovata"})

    def do_POST(self) -> None:
        if urlsplit(self.path).path != "/compress":
            self._json(404, {"error": "Funzione non trovata"})
            return
        try:
            length = int(self.headers.get("Content-Length", "0"))
            if not 0 < length <= MAX_BYTES + 1024 * 1024:
                self._json(413, {"error": "Caricamento troppo grande"})
                return
            ctype = self.headers.get("Content-Type", "")
            if not ctype.startswith("multipart/form-data;"):
                self._json(400, {"error": "Richiesta multipart necessaria"})
                return
            envelope = (b"MIME-Version: 1.0\r\nContent-Type: " +
                        ctype.encode("ascii") + b"\r\n\r\n" +
                        self.rfile.read(length))
            message = BytesParser(policy=policy.default).parsebytes(envelope)

            pdf = None
            quality = "bilanciata"
            grayscale = False
            for part in message.iter_parts():
                name = part.get_param("name", header="Content-Disposition")
                payload = part.get_payload(decode=True) or b""
                if name == "file":
                    pdf = payload
                elif name == "quality":
                    quality = payload.decode("utf-8", "replace")
                elif name == "grayscale":
                    grayscale = payload == b"on"
            if pdf is None:
                self._json(400, {"error": "Nessun PDF ricevuto"})
                return
            result, pages = optimize_pdf(pdf, quality, grayscale)
            self._send(200, result, "application/pdf", {
                "X-Original-Bytes": str(len(pdf)),
                "X-Output-Bytes": str(len(result)),
                "X-Pages": str(pages),
                "X-OCR-Note": "Regenerated by Tesseract",
            })
        except OptimizationError as exc:
            self._json(422, {"error": str(exc)})
        except (ValueError, UnicodeError):
            self._json(400, {"error": "Richiesta non valida"})
        except Exception:
            self._json(500, {"error": "Errore interno: controlla il log del server"})


if __name__ == "__main__":
    print(f"PDF Optimizer sulla porta {PORT}", flush=True)
    ThreadingHTTPServer(("0.0.0.0", PORT), Handler).serve_forever()
